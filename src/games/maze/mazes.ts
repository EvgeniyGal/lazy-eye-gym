export type MazeId = 'classic' | 'lanes' | 'islands' | 'coil' | 'keep';

export type Dir = { x: number; y: number };

export type MazeDef = {
  id: MazeId;
  /** 1 = wall, 0 = path, 2 = nest door (ghosts only). */
  grid: number[][];
  tunnelRow: number;
  playerStart: { r: number; c: number };
  nest: { r: number; c: number };
  nestRect: { r0: number; r1: number; c0: number; c1: number };
  fruitCell: { r: number; c: number };
  powerCells: { r: number; c: number }[];
  ghostStarts: { r: number; c: number; dir: Dir }[];
};

