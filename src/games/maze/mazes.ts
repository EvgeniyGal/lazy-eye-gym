const MAZES: Record<MazeId, MazeDef> = {
  classic: CLASSIC,
  lanes: LANES,
  islands: ISLANDS,
  coil: COIL,
  keep: KEEP,
};

export function getMaze(id: string | undefined): MazeDef {
  if (id && id in MAZES) return MAZES[id as MazeId];
  return CLASSIC;
}

export function mazeRows(maze: MazeDef) {
  return maze.grid.length;
}

export function mazeCols(maze: MazeDef) {
  return maze.grid[0]!.length;
}

export function walkable(maze: MazeDef, r: number, c: number, forGhost = false) {
  const rows = mazeRows(maze);
  const cols = mazeCols(maze);
  if (r < 0 || r >= rows) return false;
  let cc = c;
  if (r === maze.tunnelRow) {
    if (c < 0) cc = cols - 1;
    if (c >= cols) cc = 0;
  } else if (c < 0 || c >= cols) return false;
  const cell = maze.grid[r]![cc]!;
  if (cell === 0) return true;
  if (forGhost && cell === 2) return true;
  return false;
}

export function wrapC(maze: MazeDef, r: number, c: number) {
  const cols = mazeCols(maze);
  if (r === maze.tunnelRow) {
    if (c < 0) return cols - 1;
    if (c >= cols) return 0;
  }
  return c;
}

export function pelletCells(maze: MazeDef) {
  const rows = mazeRows(maze);
  const cols = mazeCols(maze);
  const { nestRect, powerCells } = maze;
  const powerKey = new Set(powerCells.map((p) => `${p.r},${p.c}`));
  const pellets: { r: number; c: number }[] = [];
  const powers: { r: number; c: number }[] = [];
  for (let r = 0; r < rows; r += 1) {
    for (let c = 0; c < cols; c += 1) {
      if (maze.grid[r]![c] !== 0) continue;
      if (r >= nestRect.r0 && r <= nestRect.r1 && c >= nestRect.c0 && c <= nestRect.c1) continue;
      if (powerKey.has(`${r},${c}`)) powers.push({ r, c });
      else pellets.push({ r, c });
    }
  }
  return { pellets, powers };
}

export function scatterCorners(maze: MazeDef) {
  const rows = mazeRows(maze);
  const cols = mazeCols(maze);
  return {
    chase: { r: 1, c: cols - 2 },
    ambush: { r: 1, c: 1 },
    patrol: { r: rows - 2, c: cols - 2 },
    wander: { r: rows - 2, c: 1 },
  } as const;
}
