export function wavesForDifficulty(difficulty: 'easy' | 'hard' | 'extraHard'): WaveLayout[] {
  if (difficulty === 'hard') return HARD_WAVES;
  if (difficulty === 'extraHard') return EXTRA_HARD_WAVES;
  return EASY_WAVES;
}

export function kindHp(code: number): number {
  if (code === 4) return 4;
  if (code === 3) return 3;
  if (code === 2) return 2;
  return 1;
}
